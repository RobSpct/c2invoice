function uebersetze(de) {
  if (SPRACHE === 'de') return de;
  const e = EN[de];
  return e === undefined ? de : e;
}

/* Fest im HTML stehender Text traegt data-i18n (bzw. data-i18n-title,
   -placeholder, -aria-label). Der deutsche Text wird beim ersten Wechsel in
   data-de* gesichert, damit der Rueckweg keine zweite Wortliste braucht. */
function uebersetzeHtml(wurzel) {
  const w = wurzel || document;
  for (const el of w.querySelectorAll('[data-i18n]')) {
    if (!el.dataset.de) el.dataset.de = el.textContent;
    el.textContent = uebersetze(el.dataset.de);
  }
  for (const a of ['title', 'placeholder', 'aria-label']) {
    const schluessel = 'data-i18n-' + a;
    for (const el of w.querySelectorAll('[' + schluessel + ']')) {
      const merk = 'de' + a.replace(/-([a-z])/g, (m, c) => c.toUpperCase());
      if (!el.dataset[merk]) el.dataset[merk] = el.getAttribute(a) || '';
      el.setAttribute(a, uebersetze(el.dataset[merk]));
    }
  }
}
